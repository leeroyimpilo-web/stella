@Composable
private fun LottoRoot(db: LottoDatabase) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var tab by rememberSaveable { mutableIntStateOf(0) }
    var selectedId by rememberSaveable { mutableStateOf("lotto") }
    var strategy by rememberSaveable { mutableStateOf("Quick Pick") }
    var lineCount by rememberSaveable { mutableIntStateOf(5) }
    var drawList by remember { mutableStateOf(emptyList<Draw>()) }
    var saved by remember { mutableStateOf(emptyList<Ticket>()) }
    var generated by remember { mutableStateOf(emptyList<Ticket>()) }
    var neoNumbers by rememberSaveable { mutableStateOf(listOf(7, 14, 22, 28, 36, 41)) }
    var busy by remember { mutableStateOf(false) }
    var info by remember { mutableStateOf("Offline database ready") }
    val game = games.firstOrNull { it.id == selectedId } ?: games.first()

    fun reload() {
        scope.launch {
            val pair = withContext(Dispatchers.IO) { db.allDraws() to db.savedTickets() }
            drawList = pair.first
            saved = pair.second
        }
    }
    fun sync(force: Boolean) {
        if (busy) return
        scope.launch {
            busy = true
            try {
                val result = DrawSync.update(context, db, force)
                info = if (result > 0) "Source refreshed · $result records checked" else "Results checked recently"
            } catch (_: Exception) {
                info = "Offline · showing locally saved results"
            } finally {
                busy = false
                reload()
            }
        }
    }
    LaunchedEffect(Unit) {
        try {
            withContext(Dispatchers.IO) { db.loadBundledIfEmpty() }
            reload()
            sync(false)
        } catch (_: Exception) {
            info = "Database unavailable · retry later"
        }
    }

    val gameDraws = remember(drawList, selectedId) { drawList.filter { it.game == selectedId } }

    Scaffold(
        containerColor = Background,
        topBar = {
            if (tab != 0) Row(
                Modifier.fillMaxWidth().background(Background)
                    .padding(horizontal = 17.dp, vertical = 10.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text("SA", color = White, fontWeight = FontWeight.Black, fontSize = 23.sp)
                Text("Lotto", color = Yellow, fontWeight = FontWeight.Black, fontSize = 23.sp)
                Spacer(Modifier.width(13.dp))
                Text(info, color = Muted, fontSize = 11.sp,
                    modifier = Modifier.weight(1f), maxLines = 1, overflow = TextOverflow.Ellipsis)
                TextButton(onClick = { sync(true) }, enabled = !busy) {
                    Text(if (busy) "Syncing" else "↻ Sync", color = Green)
                }
            }
        },
        bottomBar = {
            NeoBottomBar(tab) { target ->
                tab = target
                if (target == 0 || target == 1) selectedId = "lotto"
            }
        }
    ) { padding ->
        Box(Modifier.fillMaxSize().padding(padding)) {
            if (tab == 0) {
                NeoHome(
                    latest = drawList.firstOrNull { it.game == "lotto" },
                    selected = neoNumbers,
                    onSelectedChange = { value ->
                        neoNumbers = value.distinct().filter { it in 1..52 }.take(6).sorted()
                    },
                    onQuickPick = {
                        neoNumbers = NumberGenerator.generate(games.first(), 1, false)
                            .firstOrNull()?.numbers.orEmpty()
                    },
                    onSaveSelection = {
                        val valid = neoNumbers.distinct().sorted()
                        if (valid.size == 6 && valid.all { it in 1..52 }) {
                            scope.launch {
                                withContext(Dispatchers.IO) {
                                    db.saveTickets(listOf(Ticket(game = "lotto", numbers = valid)))
                                }
                                info = "Six Lotto numbers saved offline"
                                reload()
                                selectedId = "lotto"
                                tab = 4
                            }
                        }
                    },
                    onPlay = { selectedId = "lotto"; tab = 2 },
                    onResults = { selectedId = "lotto"; tab = 1 },
                    onMore = { tab = 5 },
                    onSync = { sync(true) }
                )
            } else if (tab == 5) {
                NeoMore(onAnalyse = { tab = 3 }, onSaved = { tab = 4 },
                    onSync = { sync(true) }, status = info)
            } else {
                Column(Modifier.fillMaxSize().background(Background)) {
                    LazyRow(
                        modifier = Modifier.fillMaxWidth(),
                        contentPadding = PaddingValues(horizontal = 14.dp, vertical = 8.dp),
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        items(games, key = { it.id }) { option ->
                            FilterChip(
                                selected = game.id == option.id,
                                onClick = { selectedId = option.id; generated = emptyList() },
                                label = { Text(option.name, fontSize = 12.sp) },
                                colors = FilterChipDefaults.filterChipColors(
                                    selectedContainerColor = Yellow, selectedLabelColor = Background
                                )
                            )
                        }
                    }
                    when (tab) {
                        1 -> DrawScreen(game, gameDraws,
                            onPdf = {
                                ExportFiles.sharePdf(context, game.name + " Draw History",
                                    gameDraws.map { it.date + "  " + it.numbers.joinToString(" - ") +
                                        (it.bonus?.let { b -> "  + " + b } ?: "") })
                            },
                            onJpeg = {
                                ExportFiles.shareJpeg(context, game.name + " Draws",
                                    gameDraws.take(33).map { it.date + "  " + it.numbers.joinToString(" - ") })
                            })
                        2 -> GenerateScreen(
                            game = game, strategy = strategy, onStrategy = { strategy = it },
                            count = lineCount, onCount = { lineCount = it.coerceIn(1, 50) },
                            tickets = generated,
                            onGenerate = { generated = NumberGenerator.generate(game, lineCount, strategy == "Spread") },
                            onSave = {
                                if (generated.isNotEmpty()) {
                                    scope.launch {
                                        withContext(Dispatchers.IO) { db.saveTickets(generated) }
                                        info = generated.size.toString() + " lines saved offline"
                                        reload()
                                    }
                                }
                            },
                            onPdf = {
                                if (generated.isNotEmpty())
                                    ExportFiles.sharePdf(context, game.name + " Picks", generated.map(::ticketText))
                            },
                            onJpeg = {
                                if (generated.isNotEmpty())
                                    ExportFiles.shareJpeg(context, game.name + " Picks", generated.map(::ticketText))
                            })
                        3 -> AnalyzeScreen(game, gameDraws,
                            onPdf = { ExportFiles.sharePdf(context, game.name + " Frequencies", frequencyRows(gameDraws)) },
                            onJpeg = { ExportFiles.shareJpeg(context, game.name + " Frequencies", frequencyRows(gameDraws)) })
                        else -> SavedScreen(saved.filter { it.game == game.id },
                            onDelete = { id ->
                                scope.launch {
                                    withContext(Dispatchers.IO) { db.deleteTicket(id) }
                                    reload()
                                }
                            },
                            onPdf = {
                                ExportFiles.sharePdf(context, game.name + " Saved Picks",
                                    saved.filter { it.game == game.id }.map(::ticketText))
                            },
                            onJpeg = {
                                ExportFiles.shareJpeg(context, game.name + " Saved Picks",
                                    saved.filter { it.game == game.id }.map(::ticketText))
                            })
                    }
                }
            }
        }
    }
}

private fun ticketText(ticket: Ticket): String =
    ticket.numbers.joinToString(" - ") { it.toString().padStart(2, '0') } +
        (ticket.powerBall?.let { "  PB: ${it.toString().padStart(2, '0')}" } ?: "")

private fun frequencyRows(draws: List<Draw>): List<String> =
    draws.flatMap { it.numbers }
        .groupingBy { it }.eachCount()
        .entries.sortedWith(compareByDescending<Map.Entry<Int, Int>> { it.value }.thenBy { it.key })
        .map { "Number ${it.key.toString().padStart(2, '0')}  ·  ${it.value} appearances" }

@Composable
private fun Heading(title: String, subtitle: String) {
    Column(Modifier.padding(bottom = 14.dp)) {
        Text(title, fontSize = 25.sp, fontWeight = FontWeight.ExtraBold)
        Text(subtitle, fontSize = 12.sp, color = Muted)
    }
}

@Composable
private fun LottoPanel(modifier: Modifier = Modifier, content: @Composable ColumnScope.() -> Unit) {
    Card(
        modifier = modifier,
        colors = CardDefaults.cardColors(containerColor = Panel),
        shape = RoundedCornerShape(20.dp)
    ) { Column(Modifier.fillMaxWidth().padding(16.dp), content = content) }
}

@Composable
private fun Balls(numbers: List<Int>, bonus: Int? = null, isPower: Boolean = false) {
    Row(horizontalArrangement = Arrangement.spacedBy(6.dp), verticalAlignment = Alignment.CenterVertically) {
        numbers.forEach { n ->
            Box(
                Modifier.size(37.dp).background(Yellow, CircleShape),
                contentAlignment = Alignment.Center
            ) {
                Text(n.toString().padStart(2, '0'), color = Background, fontWeight = FontWeight.Bold, fontSize = 13.sp)
            }
        }
        if (bonus != null) {
            Box(
                Modifier.size(37.dp).background(if (isPower) Color(0xFFEA4550) else Color(0xFF6A7180), CircleShape),
                contentAlignment = Alignment.Center
            ) {
                Text(bonus.toString().padStart(2, '0'), color = Color.White, fontWeight = FontWeight.Bold, fontSize = 13.sp)
            }
        }
    }
}

