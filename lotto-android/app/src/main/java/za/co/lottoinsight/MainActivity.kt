@Composable
private fun DrawScreen(game: LottoGame, draws: List<Draw>, onPdf: () -> Unit, onJpeg: () -> Unit) {
    var query by remember(game.id) { mutableStateOf("") }
    val shown = remember(draws, query) {
        draws.filter { query.isBlank() || it.date.contains(query.trim()) }.take(300)
    }
    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        item {
            Heading("Draw archive", "${draws.size} offline ${game.name} results")
            OutlinedTextField(
                value = query, onValueChange = { query = it.take(12) },
                label = { Text("Search date (YYYY-MM-DD)") },
                modifier = Modifier.fillMaxWidth(), singleLine = true
            )
            Spacer(Modifier.height(10.dp))
            ExportButtons(onPdf, onJpeg, draws.isNotEmpty())
        }
        items(shown, key = { "${it.game}_${it.date}" }) { draw ->
            LottoPanel {
                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                    Text(draw.date, fontWeight = FontWeight.Bold)
                    Text(if (draw.verified) "Source verified" else "Unverified", color = Muted, fontSize = 11.sp)
                }
                Spacer(Modifier.height(14.dp))
                Balls(draw.numbers, draw.bonus, game.powerBallMax > 0)
            }
        }
        if (shown.isEmpty()) item { Text("No matching results stored.", color = Muted) }
        item { Text("Displaying up to 300 rows; PDF exports all stored rows.", color = Muted, fontSize = 11.sp) }
    }
}

@Composable
private fun GenerateScreen(
    game: LottoGame, strategy: String, onStrategy: (String) -> Unit,
    count: Int, onCount: (Int) -> Unit, tickets: List<Ticket>,
    onGenerate: () -> Unit, onSave: () -> Unit,
    onPdf: () -> Unit, onJpeg: () -> Unit
) {
    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(13.dp)
    ) {
        item {
            Heading("Number generator", "Create up to 50 unique number lines")
            LottoPanel {
                Text("SELECTION METHOD", color = Muted, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                Spacer(Modifier.height(8.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    listOf("Quick Pick", "Spread").forEach { option ->
                        FilterChip(
                            selected = strategy == option, onClick = { onStrategy(option) },
                            label = { Text(option) },
                            colors = FilterChipDefaults.filterChipColors(
                                selectedContainerColor = Yellow, selectedLabelColor = Background
                            )
                        )
                    }
                }
                Text(
                    if (strategy == "Quick Pick") "Uniform random selections."
                    else "One random number from each range segment. This changes selection patterns, not draw odds.",
                    fontSize = 12.sp, color = Muted
                )
                Spacer(Modifier.height(16.dp))
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Text("Number of lines", modifier = Modifier.weight(1f), fontWeight = FontWeight.Medium)
                    OutlinedButton(onClick = { onCount(count - 1) }, enabled = count > 1) { Text("−") }
                    Text(" $count ", fontWeight = FontWeight.Bold, fontSize = 18.sp)
                    OutlinedButton(onClick = { onCount(count + 1) }, enabled = count < 50) { Text("+") }
                }
                Spacer(Modifier.height(13.dp))
                Button(onClick = onGenerate, modifier = Modifier.fillMaxWidth()) {
                    Text("✦ Generate ${game.name} Lines", fontWeight = FontWeight.Bold)
                }
            }
        }
        if (tickets.isNotEmpty()) item {
            LottoPanel {
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                    Text("${tickets.size} GENERATED LINES", fontWeight = FontWeight.Bold, color = Yellow, modifier = Modifier.weight(1f))
                    TextButton(onClick = onSave) { Text("Save all") }
                }
                Spacer(Modifier.height(5.dp))
                ExportButtons(onPdf, onJpeg, true)
            }
        }
        items(tickets) { ticket ->
            LottoPanel {
                Text("LINE ${tickets.indexOf(ticket) + 1}", color = Muted, fontSize = 11.sp)
                Spacer(Modifier.height(9.dp))
                Balls(ticket.numbers, ticket.powerBall, game.powerBallMax > 0)
            }
        }
        if (tickets.isEmpty()) item { Text("Select a method and tap Generate to create your first lines.", color = Muted) }
        item { Text("Unofficial suggestions, not purchased lottery tickets. Every valid line has the same draw probability.", color = Muted, fontSize = 11.sp) }
    }
}

@Composable
private fun AnalyzeScreen(game: LottoGame, draws: List<Draw>, onPdf: () -> Unit, onJpeg: () -> Unit) {
    val counts = remember(draws) {
        draws.flatMap { it.numbers }.groupingBy { it }.eachCount()
    }
    val ranked = counts.entries.sortedWith(compareByDescending<Map.Entry<Int, Int>> { it.value }.thenBy { it.key })
    val peak = ranked.firstOrNull()?.value ?: 1
    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(10.dp)
    ) {
        item {
            Heading("Number analytics", "Historical frequencies, not predictions")
            LottoPanel {
                Text("${draws.size} draws analysed", color = Yellow, fontSize = 23.sp, fontWeight = FontWeight.Bold)
                Text("Historic game rules and number ranges changed over time.", color = Muted, fontSize = 12.sp)
                Spacer(Modifier.height(9.dp))
                ExportButtons(onPdf, onJpeg, ranked.isNotEmpty())
            }
        }
        items(ranked.take(30)) { entry ->
            LottoPanel {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Box(
                        Modifier.size(39.dp).background(Yellow, CircleShape),
                        contentAlignment = Alignment.Center
                    ) {
                        Text(entry.key.toString().padStart(2,'0'), fontWeight = FontWeight.Bold, color = Background)
                    }
                    Spacer(Modifier.width(12.dp))
                    Column(Modifier.weight(1f)) {
                        Text("${entry.value} historical appearances", fontWeight = FontWeight.Medium, fontSize = 13.sp)
                        Spacer(Modifier.height(8.dp))
                        Box(Modifier.fillMaxWidth().height(6.dp).background(Color(0xFF353B42), CircleShape)) {
                            Box(Modifier.fillMaxWidth(entry.value.toFloat() / peak).height(6.dp).background(Green, CircleShape))
                        }
                    }
                }
            }
        }
        if (ranked.isEmpty()) item { Text("No historical data is currently available for ${game.name}.", color = Muted) }
        item { InfoNotice() }
    }
}

@Composable
private fun SavedScreen(tickets: List<Ticket>, onDelete: (Long) -> Unit, onPdf: () -> Unit, onJpeg: () -> Unit) {
    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        item {
            Heading("Saved number lines", "Stored privately on this device")
            ExportButtons(onPdf, onJpeg, tickets.isNotEmpty())
        }
        items(tickets, key = { it.id }) { ticket ->
            LottoPanel {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Text(ticket.created, modifier = Modifier.weight(1f), color = Muted, fontSize = 12.sp)
                    TextButton(onClick = { onDelete(ticket.id) }) { Text("Delete") }
                }
                Balls(ticket.numbers, ticket.powerBall, ticket.game.startsWith("powerball"))
            }
        }
        if (tickets.isEmpty()) item {
            Text("No saved lines for this game. Generate some and tap Save all.", color = Muted)
        }
        item { Text("Saved lines do not represent purchased entries.", color = Muted, fontSize = 11.sp) }
    }
}

@Composable
private fun ExportButtons(onPdf: () -> Unit, onJpeg: () -> Unit, enabled: Boolean) {
    Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
        OutlinedButton(onClick = onPdf, enabled = enabled, modifier = Modifier.weight(1f)) { Text("↓ PDF") }
        OutlinedButton(onClick = onJpeg, enabled = enabled, modifier = Modifier.weight(1f)) { Text("↓ JPEG") }
    }
}
